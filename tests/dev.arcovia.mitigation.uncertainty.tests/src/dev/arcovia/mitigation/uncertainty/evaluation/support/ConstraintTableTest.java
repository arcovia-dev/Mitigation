package dev.arcovia.mitigation.uncertainty.evaluation.support;

import dev.arcovia.mitigation.uncertainty.evaluation.EvaluationArtifacts;
import dev.arcovia.mitigation.uncertainty.evaluation.EvaluationConstraints;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;

import java.nio.file.Path;
import java.util.Arrays;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;

/**
 * Emits the constraint table of the thesis from the constraints the suites execute.
 */
public class ConstraintTableTest {

    @Test
    @EnabledIfSystemProperty(named = "arcovia.evaluation", matches = "true",
            disabledReason = "opt-in evaluation run; set -Darcovia.evaluation=true")
    public void emitsOneRowPerDeclaredConstraint() throws Exception {

        var declared = EvaluationConstraints.tableRows();
        var table = render(declared);
        System.out.println(table);
        writeArtifacts(table);

        assertFalse(declared.isEmpty(), "the evaluation must declare at least one constraint");
        assertEquals(declared.size(), declared.stream().map(EvaluationConstraints.TableRow::id).distinct().count(),
                "two constraints share an identifier, so the table would carry a duplicate row");
    }

    /**
     * Renders the table body, one row per declared constraint.
     */
    private static String render(List<EvaluationConstraints.TableRow> declared) {
        var sb = new StringBuilder();
        sb.append("% Generated by ConstraintTableTest. Input as tables/generated/eval-constraints.\n");
        String previousFamily = null;
        for (var entry : declared) {
            var family = entry.id().replaceAll("\\d+$", "");
            if (previousFamily != null && !family.equals(previousFamily)) {
                sb.append("        \\addlinespace\n");
            }
            previousFamily = family;
            var constraint = entry.members().isEmpty() ? latex(predicate(entry)) : together(entry.members());
            sb.append(String.format("        %s & %s & %s \\\\%n", entry.id(), constraint, entry.origin()));
        }
        sb.append("        \\bottomrule\n");
        return sb.toString();
    }

    private static String together(List<String> members) {
        var last = members.get(members.size() - 1);
        var rest = String.join(", ", members.subList(0, members.size() - 1));
        return rest + " and " + last + " together";
    }

    private static String predicate(EvaluationConstraints.TableRow entry) {
        return entry.predicate()
                .replaceFirst("^-\\s*\\w+:\\s*", "")
                .replaceAll("\\s+", " ")
                .trim();
    }

    private static String latex(String dsl) {
        var cell = new StringBuilder();
        Arrays.stream(dsl.split(" ")).forEach(token -> {
            if (!cell.isEmpty()) {
                cell.append(' ');
            }
            cell.append("\\softcode{").append(escape(token)).append('}');
        });
        return cell.toString();
    }

    private static String escape(String token) {
        return token.replace("\\", "\\textbackslash{}")
                .replace("_", "\\_")
                .replace("%", "\\%")
                .replace("&", "\\&")
                .replace("#", "\\#")
                .replace("$", "\\$");
    }

    private void writeArtifacts(String table) throws Exception {
        Path directory = EvaluationArtifacts.createRunDirectory(
                Path.of(System.getProperty("user.dir")), "constraint-table");
        EvaluationArtifacts.write(directory, "tab-eval-constraints.tex", table);
        System.out.println("Evaluation artefacts: " + directory);
    }
}
